// Builds demo-data.js for the replay page from the recorded runs of the final benchmark (benchmark/results.json,
// or benchmark/sample.json before the full run, or the results file named on the command line). Nothing is invented: every card, bar and check on the page is
// one of these records. Run: node build_demo_data.mjs
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = path.dirname(fileURLToPath(import.meta.url));
const B = path.join(ROOT, "benchmark");
const src = process.argv[2] || (fs.existsSync(path.join(B, "results.json")) ? "results.json" : "sample.json");
const res = JSON.parse(fs.readFileSync(path.join(B, src), "utf8"));
const pl = JSON.parse(fs.readFileSync(path.join(ROOT, "resources", "price_list.json"), "utf8"));
const ORDER = ["A1", "A2", "A6", "B2", "B5", "B7", "B8", "C2", "C3", "C4", "C6", "D1", "D3", "D4", "F1", "F7"];

const runs = res.results.map((r) => {
  const rec = JSON.parse(fs.readFileSync(path.join(B, "runs", `${r.run_id}.json`), "utf8"));
  return {
    run_id: rec.run_id, id: rec.id, group: rec.group, title: rec.title, mode: rec.mode, started: rec.started, model: rec.model,
    pass: rec.score.pass, checks: rec.score.checks, notes: rec.score.notes, fault: rec.fault, cost_usd: rec.cost_usd, ms: rec.ms,
    steps: rec.steps.map((S) => ({
      message: S.message, ms: S.ms, model_calls: S.modelCalls, writing: S.writing,
      facts: S.facts ? { status: S.facts.status, tone: S.facts.tone, channels: S.facts.channels, skus: S.facts.skus, facts: S.facts.facts, owner_issues: S.facts.owner_issues, error: S.facts.error || null } : null,
      timeline: S.timeline,
      tool_log: S.toolLog.map((l) => ({ t: l.t, agent: l.agent, agent_id: l.agent_id, version: l.version, owner: l.owner, event: l.event, tool: l.tool, detail: l.detail ?? null })),
      channels: S.channels, owner_questions: S.ownerQuestions, reviews: S.reviews, deliveries: S.deliveries,
      reply: S.result?.text || "", stop: S.stop || null,
    })),
  };
}).sort((a, b) => ORDER.indexOf(a.id) - ORDER.indexOf(b.id) || (a.mode === b.mode ? a.run_id.localeCompare(b.run_id) : a.mode === "parallel" ? -1 : 1));

const out = { source: src, generated: new Date().toISOString(), model: res.model, summary: res.summary, price_list: { period: pl.campaign_period, categories: pl.categories, clauses: pl.clauses, items: pl.items }, runs };
fs.writeFileSync(path.join(ROOT, "demo-data.js"), `// Generated by build_demo_data.mjs from benchmark/${src}. Do not edit by hand.\nwindow.KIDDOZ = ${JSON.stringify(out)};\n`);
console.log(`demo-data.js: ${runs.length} runs from ${src}, ${(fs.statSync(path.join(ROOT, "demo-data.js")).size / 1024).toFixed(0)} KB`);
